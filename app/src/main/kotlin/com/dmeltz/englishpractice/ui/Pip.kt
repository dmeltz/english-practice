@DrawableRes
fun pipDrawable(mood: Mood, alt: Boolean): Int = when (mood) {
    Mood.HAPPY -> if (alt) R.drawable.pip_happy_alt else R.drawable.pip_happy
    Mood.CALM -> if (alt) R.drawable.pip_calm_alt else R.drawable.pip_calm
    Mood.WAITING -> if (alt) R.drawable.pip_waiting_alt else R.drawable.pip_waiting
    Mood.ANNOYED -> if (alt) R.drawable.pip_annoyed_alt else R.drawable.pip_annoyed
    Mood.ANGRY -> if (alt) R.drawable.pip_angry_alt else R.drawable.pip_angry
}

/**
 * Pip, animated: bobs gently and blinks; bounces when happy; shakes and puffs steam when angry.
 * The pictures are the same drawables the widget uses (generated by tools/gen_mascot.py).
 */
@Composable
fun Pip(mood: Mood, size: Dp, modifier: Modifier = Modifier) {
    var alt by remember { mutableStateOf(false) }
    LaunchedEffect(mood) {
        alt = false
        while (true) {
            when (mood) {
                // Alternate steam puffs.
                Mood.ANGRY -> { delay(350); alt = !alt }
                // A little hop now and then.
                Mood.HAPPY -> { delay(Random.nextLong(1200, 2200)); alt = true; delay(220); alt = false }
                // Blink.
                else -> { delay(Random.nextLong(2200, 4500)); alt = true; delay(140); alt = false }
            }
        }
    }
    val transition = rememberInfiniteTransition(label = "pip")
    val bob by transition.animateFloat(
        initialValue = -1f, targetValue = 1f,
        animationSpec = infiniteRepeatable(
            tween(if (mood == Mood.ANGRY) 90 else 1600, easing = if (mood == Mood.ANGRY) LinearEasing else FastOutSlowInEasing),
            RepeatMode.Reverse,
        ),
        label = "bob",
    )
    val sizePx = size.value
    Image(
        painter = painterResource(pipDrawable(mood, alt)),
        contentDescription = "Pip",
        modifier = modifier.size(size).graphicsLayer {
            when (mood) {
                Mood.ANGRY -> translationX = bob * sizePx * 0.03f * density
                Mood.ANNOYED -> rotationZ = bob * 3f
                else -> translationY = bob * sizePx * 0.025f * density
            }
        },
    )
}

/** Pip with a speech bubble next to it. */
@Composable
fun PipSays(mood: Mood, text: String, modifier: Modifier = Modifier, size: Dp = 72.dp) {
    Row(
        modifier.fillMaxWidth(),
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.spacedBy(10.dp),
    ) {
        Pip(mood, size)
        Surface(
            color = MaterialTheme.colorScheme.surfaceContainerHigh,
            shape = RoundedCornerShape(topStart = 4.dp, topEnd = 16.dp, bottomEnd = 16.dp, bottomStart = 16.dp),
            modifier = Modifier.weight(1f),
        ) {
            Text(text, style = MaterialTheme.typography.bodyLarge, modifier = Modifier.padding(12.dp))
        }
    }
}
